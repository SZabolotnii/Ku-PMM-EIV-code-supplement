# --------------------------------------------------------------------------
def load_csv(path: Path) -> list[dict]:
    with open(path, newline='') as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k, v in list(r.items()):
            if k in STR_FIELDS:
                continue
            try:
                r[k] = float(v)
            except (TypeError, ValueError):
                r[k] = float('nan')
    return rows


def sel(rows, **kw):
    out = rows
    for k, v in kw.items():
        out = [r for r in out if r[k] == v]
    return out


