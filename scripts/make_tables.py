# ==========================================================================
def _tex_escape(s: str) -> str:
    """Escape a parsed description for LaTeX, keeping comparisons in math."""
    # order matters: the symbol names are consumed before the comparisons,
    # otherwise ' >= ' eats the space that delimits 'c3'
    marks = [('TC-PMM2*', '\x06'), ('ARE*', '\x0b'), ('|dbeta|', '\x07'),
             ('c3', '\x0c'),
             (' >= ', '\x01'), (' <= ', '\x02'), (' < ', '\x03'),
             (' > ', '\x04'), (' == ', '\x05')]
    for k, v in marks:
        s = s.replace(k, v)
    for ch in ('\\', '&', '%', '$', '#', '_', '{', '}'):
        s = s.replace(ch, '\\' + ch)
    s = s.replace('~', r'\textasciitilde{}').replace('^', r'\textasciicircum{}')
    back = {'\x01': r' $\geq$ ', '\x02': r' $\leq$ ', '\x03': ' $<$ ',
            '\x04': ' $>$ ', '\x05': ' $=$ ', '\x06': r'TC-PMM2$^{*}$',
            '\x07': r'$|\Delta\beta|$', '\x0b': r'ARE$^{*}$', '\x0c': r'$c_3$'}
    for k, v in back.items():
        s = s.replace(k, v)
    # the sample size is always a bare 'n' in these descriptions
    s = re.sub(r'(?<![A-Za-z\\])n(?![A-Za-z])', '$n$', s)
    return s


def tab_gates():
    text = VERIF.read_text()
    desc = {}
    for m in re.finditer(r'^\[(PASS|FAIL)\]\s+(\S+)\s+(.*)$', text, re.M):
        desc[m.group(2)] = (m.group(1), m.group(3).strip())
    order, body = [], []
    n_pass = 0
    for m in re.finditer(r'^\s{2}(G\d\w?|C\d)\s+(PASS|FAIL)\s+(\d+)/(\d+)\s+'
                         r'sub-checks\s*$', text, re.M):
        gate, status, ok, tot = m.group(1), m.group(2), m.group(3), m.group(4)
        order.append(gate)
        n_pass += (status == 'PASS')
        d = desc.get(gate, ('', ''))[1]
        stat = status if status == 'PASS' else bold(status)
        body.append(' & '.join([gate, _tex_escape(d), stat,
                                f'{ok}/{tot}']) + r' \\')
    tot_m = re.search(r'^(\d+)/(\d+) checks passed', text, re.M)
    if tot_m:
        body.append(r'\midrule')
        body.append(r'\multicolumn{3}{l}{gates passed} & '
                    f'{tot_m.group(1)}/{tot_m.group(2)}' + r' \\')
    header = [r'Gate & Requirement & Status & Sub-checks passed \\']
    write('tab_gates.tex',
          'verification gates, run "confirmatory" (M = 2000, 180 cells)',
          'l p{0.52\\linewidth} l r', header, body)

    PROV['tab_gates.tex'] = {
        'what': 'The pre-registered verification gates with their status and the '
                'number of sub-checks passed.',
        'sources': [
            {'file': 'evidence/confirmatory/verification_report.txt',
             'columns': ['the [PASS]/[FAIL] gate headings and the closing '
                         'summary block'],
             'filter': 'all gates in the order printed by scripts/verify.py: '
                       + ', '.join(order)},
        ],
        'aggregation': 'the report is parsed, not re-derived: gate names, statuses, '
                       'descriptions and x/y sub-check counts are taken verbatim '
                       'from the machine-written report, so the table cannot drift '
                       'from the run that produced it.',
        'rows': len(order),
        'gates_passed': f'{n_pass}/{len(order)}',
    }


