def fmt(x, nd=4):
    return 'n/a' if x != x else f'{x:.{nd}f}'


def bold(s):
    return r'\textbf{' + s + '}'


def sci(x, nd=2):
    """LaTeX scientific notation, e.g. 5.06 \\times 10^{3}."""
    if x != x:
        return 'n/a'
    import math
    e = int(math.floor(math.log10(abs(x)))) if x else 0
    return r'%.*f \times 10^{%d}' % (nd, x / 10.0 ** e, e)


def write(name, header_note, colspec, header_rows, body_rows, tabcolsep=None):
    """Assemble a booktabs tabular fragment and write it.

    ``tabcolsep`` tightens the inter-column gap inside a \\begingroup, so a wide
    table fits a portrait text block without the wrapping document having to
    shrink the font; the setting cannot leak out of the fragment.
    """
    lines = [f'% {header_note}',
             '% generated by scripts/make_tables.py -- do not edit by hand']
    if tabcolsep is not None:
        lines.append(r'\begingroup\setlength{\tabcolsep}{%s}' % tabcolsep)
    lines += [r'\begin{tabular}{' + colspec + '}', r'\toprule']
    lines += header_rows
    lines.append(r'\midrule')
    lines += body_rows
    lines += [r'\bottomrule', r'\end{tabular}']
    if tabcolsep is not None:
        lines.append(r'\endgroup')
    OUTDIR.mkdir(parents=True, exist_ok=True)
    (OUTDIR / name).write_text('\n'.join(lines) + '\n')
    print(f'  wrote {OUTDIR / name}')


