# tab_lambda_star -- empirical vs theoretical break-even reliability
# ==========================================================================
def tab_lambda_star():
    theo = {}
    with open(LAMBDA_STAR_THEORY, newline='') as fh:
        for r in csv.DictReader(fh):
            theo[(r['eps_key'], r['u_family'], float(r['b1']))] = \
                r['lambda_star_theory'].strip()

    groups: dict[tuple, list] = {}
    for r in sel(EV['ls_paired'], estimator_a='tc_pmm2_oracle',
                 estimator_b='tc_ls', param='b1'):
        if r['delta'] != 0.0 or r['eps_key'] == 'gauss':
            continue
        groups.setdefault((r['eps_key'], r['u_family'], r['b1_true']), []).append(r)

    lam_grid = sorted({r['lam'] for rs in groups.values() for r in rs})
    u_order = {'gamma_wh': 0, 'gamma_fixed': 1, 'lognormal': 2}
    body = []
    for key in sorted(groups, key=lambda k: (k[0], u_order[k[1]], -k[2])):
        rs = sorted(groups[key], key=lambda z: z['lam'])
        t = theo.get((key[0], key[1], key[2]), '')
        emp = ''
        # identical linear-interpolation rule as scripts/verify.py
        for a, b in zip(rs, rs[1:]):
            if (a['re'] - 1.0) * (b['re'] - 1.0) < 0:
                emp = ('%.4f' % (a['lam'] + (b['lam'] - a['lam'])
                                 * (1.0 - a['re']) / (b['re'] - a['re'])))
                break
        if not emp:
            if all(r['re'] < 1 for r in rs):
                # distinguish "the estimator never loses" from "the crossing
                # exists but sits below the simulated grid"
                if t and float(t) < min(lam_grid):
                    emp = (r'not bracketed ($\lambda\geq%.2f$ simulated)'
                           % min(lam_grid))
                else:
                    emp = r'none ($\widehat{\mathrm{RE}}<1$ throughout)'
            elif all(r['re'] > 1 for r in rs):
                emp = r'above $\lambda=%.2f$' % max(lam_grid)
            else:
                emp = 'n/a'
        t_tex = t if t else 'none'
        body.append(' & '.join([EPS_TEX[key[0]], U_TEX[key[1]],
                                f'${key[2]:+.0f}$', emp, t_tex]) + r' \\')
    header = [r'$c_3(\varepsilon)$ & $U$ & $\beta_1$ & '
              r'$\hat\lambda^{*}$ (Monte Carlo) & $\lambda^{*}$ (closed form) \\']
    write('tab_lambda_star.tex',
          'break-even reliability of the fixed-weight TC-PMM2 '
          '(RE crosses 1), slope beta1, n = 1000, M = 2000',
          'l l r l r', header, body)

    PROV['tab_lambda_star.tex'] = {
        'what': 'Break-even reliability lambda* at which the fixed-weight TC-PMM2 '
                'stops losing to TC-LS: Monte Carlo estimate against the closed '
                'form. TC-PMM2* has no break-even (ARE* <= 1 for every lambda).',
        'sources': [
            {'file': 'evidence/lambda_star/paired.csv',
             'columns': ['lam', 're'],
             'filter': "estimator_a='tc_pmm2_oracle'; estimator_b='tc_ls'; "
                       "param='b1'; delta=0; eps_key != 'gauss' (ARE is "
                       'identically 1 there, so no crossing exists); n=1000; '
                       f'lam grid {lam_grid}'},
            {'file': 'evidence/asymptotics/lambda_star_theory.csv',
             'columns': ['lambda_star_theory'],
             'filter': 'joined on (eps_key, u_family, b1); blank means the '
                       'closed-form ARE never crosses 1'},
        ],
        'aggregation': 'lambda* is obtained by linear interpolation between the two '
                       'adjacent grid reliabilities whose measured RE brackets 1 -- '
                       'byte-for-byte the rule used by scripts/verify.py, so the '
                       'table reproduces the verification report.',
        'rows': len(body),
    }


