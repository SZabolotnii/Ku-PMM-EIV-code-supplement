#!/usr/bin/env python3
"""Independent numerical verification of the TC-PMM2 asymptotics.

Verification Standard 4 (independent cross-check).  Two layers:

  (A) sandwich pieces:  M and Q estimated by brute-force Monte Carlo averaging
      of Psi and dPsi/dTheta at Theta* on one very large sample, compared with
      the closed forms generated by are_symbolic.py;

  (B) the estimator itself:  R independent replications at n = 20000, solving
      the TC-PMM2 estimating equations by Newton-Raphson started from TC-LS;
      the empirical n * Var(beta1_hat) is compared with the closed-form
      asymptotic variance, and the empirical variance ratio with ARE(lambda).

Acceptance: |closed form - MC| within ~2 MC standard errors.

Run:  .venv/bin/python theory/are_numeric_check.py
      .venv/bin/python theory/are_numeric_check.py --reps 400 --n 20000
"""

