def gamma_central_moments(shape, scale, jmax=6):
    from math import comb, factorial
    kap = {j: float(factorial(j - 1)) * shape * scale**j
           for j in range(1, jmax + 1)}
    kap[1] = 0.0
    mu = {0: 1.0, 1: 0.0}
    for n in range(2, jmax + 1):
        s = kap[n]
        for k in range(1, n):
            s += comb(n - 1, k - 1) * kap[k] * mu[n - k]
        mu[n] = s
    return mu


def normal_central_moments(var, jmax=6):
    from math import comb
    kap = {j: (var if j == 2 else 0.0) for j in range(1, jmax + 1)}
    kap[1] = 0.0
    mu = {0: 1.0, 1: 0.0}
    for n in range(2, jmax + 1):
        s = kap[n]
        for k in range(1, n):
            s += comb(n - 1, k - 1) * kap[k] * mu[n - k]
        mu[n] = s
    return mu


class Design:
    """Holds the DGP and its true moments."""

    def __init__(self, name, lam, c3, b1, udist, mux=1.0, sx=1.0, b0=1.0):
        self.name, self.lam, self.c3, self.b1 = name, lam, c3, b1
        self.udist, self.mux, self.sx, self.b0 = udist, mux, sx, b0
        self.sx2 = sx**2
        self.n2_target = self.sx2 * (1 - lam) / lam

        # eps: centred gamma standardised to m2 = 1, skewness c3 (c3=0 -> normal)
        if c3 == 0.0:
            self.eps_kind = "normal"
            me = normal_central_moments(1.0, 4)
        else:
            self.eps_kind = "gamma"
            self.ke = 4.0 / c3**2
            self.the = 1.0 / np.sqrt(self.ke)
            me = gamma_central_moments(self.ke, self.the, 4)
        self.m2, self.m3, self.m4 = me[2], me[3], me[4]

        if udist == "wh_gamma":               # W&H 6.1
            self.ku = 4.0 * (1 - lam) / lam
            self.thu = 0.5
            mu_u = gamma_central_moments(self.ku, self.thu, 6)
        elif udist.startswith("gamma_k"):
            self.ku = float(udist.split("gamma_k")[1])
            self.thu = np.sqrt(self.n2_target / self.ku)
            mu_u = gamma_central_moments(self.ku, self.thu, 6)
        elif udist == "normal":
            self.su = np.sqrt(self.n2_target)
            mu_u = normal_central_moments(self.n2_target, 6)
        else:
            raise ValueError(udist)
        self.n2, self.n3, self.n4 = mu_u[2], mu_u[3], mu_u[4]
        self.n5, self.n6 = mu_u[5], mu_u[6]

        self.a = self.m4 - self.m2**2
        self.b = self.m3
        self.c = self.m2
        self.g2 = 1 - self.m3**2 / (self.m2 * (self.m4 - self.m2**2))

    def args(self):
        return (self.mux, self.sx2, self.b1, self.m2, self.m3, self.m4,
                self.n2, self.n3, self.n4, self.n5, self.n6)

    def draw(self, rng, n):
        X = self.mux + self.sx * rng.standard_normal(n)
        if self.eps_kind == "normal":
            eps = rng.standard_normal(n)
        else:
            eps = rng.gamma(self.ke, self.the, n) - self.ke * self.the
        if self.udist == "normal":
            u = self.su * rng.standard_normal(n)
        else:
            u = rng.gamma(self.ku, self.thu, n) - self.ku * self.thu
        Y = self.b0 + self.b1 * X + eps
        Wt = X + u                     # already centred: E(U) subtracted
        return X, eps, u, Y, Wt


